import ChessCore

/// The hand-written half of the opening picker: how sharp each opening is,
/// and how the biggest families split into groups. `SpecTests` checks it
/// against `Golden/constants.json`.

/// 1 is quiet and positional, 5 a knife fight from move one.
public typealias Sharpness = Int

/// A group inside a big family: every branch reachable from one of its positions.
public struct GroupSpec: Equatable, Sendable {
  public var label: String
  /// Move orders to the positions that define the group.
  public var from: [String]
  public var sharpness: Sharpness
}

public struct FamilySplit: Equatable, Sendable {
  public var groups: [GroupSpec]
  /// What the branches no group reaches are called.
  public var rest: String
  public var restSharpness: Sharpness?
}

